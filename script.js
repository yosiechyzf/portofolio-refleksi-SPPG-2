const searchInput = document.getElementById("searchInput");
const categoryFilter = document.getElementById("categoryFilter");
const reflectionGrid = document.getElementById("reflectionGrid");
const reflectionCards = document.querySelectorAll(".reflection-card");
const reflectionDetail = document.getElementById("reflectionDetail");
const detailTitle = document.getElementById("detailTitle");
const detailContent = document.getElementById("detailContent");
const emptyMessage = document.getElementById("emptyMessage");

const menuToggle = document.getElementById("menuToggle");
const navMenu = document.getElementById("navMenu");
const printButton = document.getElementById("printButton");
const closeDetail = document.getElementById("closeDetail");
const previewPpgPdf = document.getElementById("previewPpgPdf");
const ppgPdfPreview = document.getElementById("ppgPdfPreview");

function renderReflection(index) {
  const item = reflections[index];

  if (!item) return;

  detailTitle.textContent = item.title;

  const sections = [
    {
      heading: "Connection",
      content: item.connection
    },
    {
      heading: "Challenge",
      content: item.challenge
    },
    {
      heading: "Concept",
      content: item.concept
    },
    {
      heading: "Change",
      content: item.change
    }
  ];

  const fourC = document.createElement("div");
  fourC.className = "four-c-grid";

  sections.forEach(section => {
    const card = document.createElement("article");
    card.className = "four-c-item";

    const heading = document.createElement("h4");
    heading.textContent = section.heading;

    const paragraph = document.createElement("p");
    paragraph.textContent = section.content;

    card.append(heading, paragraph);
    fourC.appendChild(card);
  });

  const artifactSection = document.createElement("section");
  artifactSection.className = "detail-extra";

  const artifactHeading = document.createElement("h4");
  artifactHeading.textContent = "Artefak yang Dipilih";

  const artifactText = document.createElement("p");
  artifactText.textContent = item.artifact;

  const reasonHeading = document.createElement("h4");
  reasonHeading.textContent = "Alasan Pemilihan Artefak";

  const reasonText = document.createElement("p");
  reasonText.textContent = item.reason;

  artifactSection.append(
    artifactHeading,
    artifactText,
    reasonHeading,
    reasonText
  );

  if (item.reflectionSupport) {
    const supportHeading = document.createElement("h4");
    supportHeading.textContent = "Bagian Artefak yang Mendukung Refleksi";

    const supportText = document.createElement("p");
    supportText.textContent = item.reflectionSupport;

    artifactSection.append(supportHeading, supportText);
  }

  const pdfLink = document.createElement("a");
  pdfLink.className = "detail-pdf-link";
  pdfLink.href = item.pdf;
  pdfLink.target = "_blank";
  pdfLink.rel = "noopener";
  pdfLink.textContent = "Buka PDF refleksi ↗";

  const artifactLink = document.createElement("a");
  artifactLink.className = "detail-pdf-link";
  artifactLink.href = item.artifactUrl;
  artifactLink.target = "_blank";
  artifactLink.rel = "noopener noreferrer";
  artifactLink.textContent = "Lihat artefak di Google Drive ↗";

  artifactSection.append(
    pdfLink,
    artifactLink
  );

  const practicalSection = document.createElement("section");
  practicalSection.className = "detail-extra";

  const practicalHeading = document.createElement("h4");
  practicalHeading.textContent = "Kaitan Praktis";

  const practicalText = document.createElement("p");
  practicalText.textContent = item.practical;

  practicalSection.append(practicalHeading, practicalText);

  detailContent.replaceChildren(
    fourC,
    artifactSection,
    practicalSection
  );

  reflectionDetail.hidden = false;
  reflectionDetail.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });
}

function filterReflections() {
  const query = searchInput.value.trim().toLowerCase();
  const category = categoryFilter.value;
  let visibleCount = 0;

  reflectionCards.forEach((card, index) => {
    const searchableText = [
      card.textContent,
      reflections[index].connection,
      reflections[index].challenge,
      reflections[index].concept,
      reflections[index].change,
      reflections[index].artifact,
      reflections[index].practical
    ].join(" ").toLowerCase();

    const matchesSearch = searchableText.includes(query);
    const matchesCategory =
      category === "all" ||
      card.dataset.category === category;

    const visible = matchesSearch && matchesCategory;

    card.hidden = !visible;

    if (visible) visibleCount++;
  });

  emptyMessage.hidden = visibleCount !== 0;

  if (visibleCount === 0) {
    reflectionGrid.setAttribute("aria-label", "Tidak ada hasil");
  } else {
    reflectionGrid.setAttribute("aria-label", "Daftar refleksi");
  }

  reflectionDetail.hidden = true;
}

document.querySelectorAll(".detail-button").forEach(button => {
  button.addEventListener("click", () => {
    const index = Number(button.dataset.reflection);
    const wasOpen = !reflectionDetail.hidden;
    const sameItem = detailTitle.textContent === reflections[index].title;

    if (wasOpen && sameItem) {
      reflectionDetail.hidden = true;
      button.setAttribute("aria-expanded", "false");
      return;
    }

    document.querySelectorAll(".detail-button").forEach(item => {
      item.setAttribute("aria-expanded", "false");
    });

    button.setAttribute("aria-expanded", "true");
    renderReflection(index);
  });
});

searchInput.addEventListener("input", filterReflections);
categoryFilter.addEventListener("change", filterReflections);

closeDetail.addEventListener("click", () => {
  reflectionDetail.hidden = true;

  document.querySelectorAll(".detail-button").forEach(button => {
    button.setAttribute("aria-expanded", "false");
  });
});

menuToggle.addEventListener("click", () => {
  const isOpen = navMenu.classList.toggle("open");

  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute(
    "aria-label",
    isOpen ? "Tutup navigasi" : "Buka navigasi"
  );
  menuToggle.textContent = isOpen ? "✕" : "☰";
});

navMenu.querySelectorAll("a").forEach(link => {
  link.addEventListener("click", () => {
    navMenu.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", "Buka navigasi");
    menuToggle.textContent = "☰";
  });
});

printButton.addEventListener("click", () => {
  window.print();
});

previewPpgPdf.addEventListener("click", () => {
  const isExpanded = previewPpgPdf.getAttribute("aria-expanded") === "true";
  const shouldShowPreview = !isExpanded;

  ppgPdfPreview.hidden = !shouldShowPreview;
  previewPpgPdf.setAttribute("aria-expanded", String(shouldShowPreview));
  previewPpgPdf.textContent = shouldShowPreview
    ? "Tutup Pratinjau"
    : "Pratinjau PDF";
});
